export function getFieldID(description) {
  const fields = customFieldInfo.data

  for (const fieldInfo of fields) {
    if (fieldInfo.name.includes(description)) {
      return {
        name: fieldInfo.name,
        description: fieldInfo.description,
        id: fieldInfo.clientCustomFieldID,
      }
    }
  }
  throw new Error("No custom field found with that description")
}